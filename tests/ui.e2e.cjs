const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '/Users/tiyukains/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 try{
 const page=await browser.newPage();
 await page.goto('http://127.0.0.1:4318');
 await page.locator('.ipynb-cell').first().waitFor();
 assert.equal(await page.locator('.ipynb-cell').first().locator('.cm-editor').count(),0);
 await page.locator('.ipynb-markdown-preview').first().evaluate(el=>{const link=document.createElement('a');link.href='#keyboard-link';link.textContent='测试链接';el.append(link)});
 await page.getByRole('link',{name:'测试链接'}).focus();
 await page.keyboard.press('Enter');
 assert.equal(await page.evaluate(()=>location.hash),'#keyboard-link');
 assert.equal(await page.locator('.ipynb-cell').first().locator('.cm-editor').count(),0);
 await page.locator('.ipynb-markdown-preview').first().dblclick();
 await page.locator('.ipynb-cell').first().locator('.cm-content').press('Shift+Enter');
 assert.equal(await page.locator('.ipynb-cell').first().locator('.cm-editor').count(),0);
 assert.ok(await page.locator('.ipynb-toolbar > button').count()<=5);
 await page.locator('.ipynb-insert-gap').last().hover();
 await page.locator('.ipynb-insert-gap').last().getByRole('button',{name:'添加代码',exact:true}).click();
 assert.equal(await page.locator('.ipynb-cell').count(),3);
 const editor=page.locator('.ipynb-cell').last().locator('.cm-content');
 await editor.fill('print("hello notebook")');
 await page.locator('.ipynb-cell').last().hover();
 await page.locator('.ipynb-cell').last().getByRole('button',{name:'运行单元格',exact:true}).click();
 await page.locator('.ipynb-cell').last().locator('.ipynb-output').getByText('hello notebook',{exact:false}).waitFor();
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await page.getByText('已保存',{exact:true}).waitFor();
 const saved=await page.evaluate(()=>window.savedNotebook);
 assert.equal(saved.cells[2].source,'print("hello notebook")');
 assert.ok(saved.cells[2].execution_count>=1);
 await page.locator('.ipynb-insert-gap').last().hover();
 await page.locator('.ipynb-insert-gap').last().getByRole('button',{name:'添加 Markdown',exact:true}).click();
 await page.locator('.ipynb-cell').last().locator('.cm-content').fill('# 学习笔记');
 await page.locator('.ipynb-cell').last().hover();
 await page.locator('.ipynb-cell').last().getByRole('button',{name:'预览',exact:true}).click();
 await page.locator('.ipynb-cell').last().locator('.ipynb-markdown-preview').getByText('学习笔记').waitFor();
 await page.locator('.ipynb-toolbar > details > summary').click();
 await page.getByRole('button',{name:'撤销',exact:true}).click();
 assert.equal(await page.locator('.ipynb-cell').count(),4);
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await page.evaluate(()=>window.simulateConflict());
 await page.locator('.ipynb-cell').nth(1).locator('.cm-content').fill('3+3');
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await page.locator('.ipynb-message').getByText('文件已在其他程序中修改',{exact:true}).waitFor();
 assert.equal(await page.locator('.ipynb-message details').getAttribute('open'),null);
 await page.locator('.ipynb-message summary').click();
 assert.ok(await page.locator('.ipynb-message pre').isVisible());
 const issues=await page.evaluate(()=>({script:document.querySelector('.ipynb-output script')!==null}));assert.equal(issues.script,false);
 await page.screenshot({path:process.env.IPYNB_SCREENSHOT||'/tmp/obsidian-ipynb-preview.png',fullPage:true});
 console.log('PASS 原生编辑、真实运行、输出、保存、Markdown预览、撤销及外部冲突');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
